package com.playground.api.config;

import com.playground.api.entity.RequestHistoryEntity;
import com.playground.api.entity.SavedRequestEntity;
import jakarta.persistence.Column;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.core.io.ClassPathResource;
import org.yaml.snakeyaml.Yaml;

import java.io.InputStream;
import java.lang.reflect.Field;
import java.nio.charset.StandardCharsets;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.*;

class PostgresConfigurationTest {

    @Test
    @DisplayName("PostgreSQL Driver: Class org.postgresql.Driver must be loadable on classpath")
    void testPostgresDriverOnClasspath() {
        assertDoesNotThrow(() -> Class.forName("org.postgresql.Driver"),
                "PostgreSQL JDBC Driver (org.postgresql.Driver) must be available on the classpath");
    }

    @Test
    @DisplayName("PostgreSQL Configuration: application-postgres.yml must exist and define PostgreSQL settings")
    void testPostgresConfigurationFile() throws Exception {
        ClassPathResource resource = new ClassPathResource("application-postgres.yml");
        assertTrue(resource.exists(), "application-postgres.yml must exist in classpath");

        Yaml yaml = new Yaml();
        try (InputStream in = resource.getInputStream()) {
            Map<String, Object> root = yaml.load(in);
            assertNotNull(root);

            @SuppressWarnings("unchecked")
            Map<String, Object> spring = (Map<String, Object>) root.get("spring");
            assertNotNull(spring, "spring block must be defined in application-postgres.yml");

            @SuppressWarnings("unchecked")
            Map<String, Object> datasource = (Map<String, Object>) spring.get("datasource");
            assertNotNull(datasource);
            assertEquals("org.postgresql.Driver", datasource.get("driver-class-name"));
            assertTrue(datasource.get("url").toString().contains("postgresql"));

            @SuppressWarnings("unchecked")
            Map<String, Object> jpa = (Map<String, Object>) spring.get("jpa");
            assertNotNull(jpa);
            @SuppressWarnings("unchecked")
            Map<String, Object> props = (Map<String, Object>) jpa.get("properties");
            assertNotNull(props);
            @SuppressWarnings("unchecked")
            Map<String, Object> hibernate = (Map<String, Object>) props.get("hibernate");
            assertNotNull(hibernate);
            assertEquals("org.hibernate.dialect.PostgreSQLDialect", hibernate.get("dialect"));

            @SuppressWarnings("unchecked")
            Map<String, Object> flyway = (Map<String, Object>) spring.get("flyway");
            assertNotNull(flyway);
            assertEquals("classpath:db/migration-postgres", flyway.get("locations"));
        }
    }

    @Test
    @DisplayName("PostgreSQL Migrations: V1 must use standard identity and TEXT types without MySQL-specific syntax")
    void testPostgresV1MigrationSyntax() throws Exception {
        ClassPathResource resource = new ClassPathResource("db/migration-postgres/V1__init_schema.sql");
        assertTrue(resource.exists(), "db/migration-postgres/V1__init_schema.sql must exist");

        String sql = new String(resource.getInputStream().readAllBytes(), StandardCharsets.UTF_8);

        // Must NOT contain MySQL AUTO_INCREMENT or LONGTEXT
        assertFalse(sql.contains("AUTO_INCREMENT"), "PostgreSQL V1 migration must not contain MySQL AUTO_INCREMENT");
        assertFalse(sql.contains("LONGTEXT"), "PostgreSQL V1 migration must not contain MySQL LONGTEXT");

        // Must contain PostgreSQL standard identity columns and TEXT
        assertTrue(sql.contains("GENERATED BY DEFAULT AS IDENTITY"), "PostgreSQL V1 must use GENERATED BY DEFAULT AS IDENTITY");
        assertTrue(sql.contains("body TEXT"), "PostgreSQL V1 must define body as TEXT");
        assertTrue(sql.contains("request_body TEXT"), "PostgreSQL V1 must define request_body as TEXT");
        assertTrue(sql.contains("response_body TEXT"), "PostgreSQL V1 must define response_body as TEXT");
    }

    @Test
    @DisplayName("PostgreSQL Migrations: V2 must include seed data and sequence synchronization")
    void testPostgresV2MigrationSyntax() throws Exception {
        ClassPathResource resource = new ClassPathResource("db/migration-postgres/V2__seed_default_data.sql");
        assertTrue(resource.exists(), "db/migration-postgres/V2__seed_default_data.sql must exist");

        String sql = new String(resource.getInputStream().readAllBytes(), StandardCharsets.UTF_8);
        assertTrue(sql.contains("Starter API Collection"));
        assertTrue(sql.contains("setval(pg_get_serial_sequence('collections'"), "PostgreSQL V2 must sync collections sequence");
        assertTrue(sql.contains("setval(pg_get_serial_sequence('environments'"), "PostgreSQL V2 must sync environments sequence");
        assertTrue(sql.contains("setval(pg_get_serial_sequence('environment_variables'"), "PostgreSQL V2 must sync env vars sequence");
        assertTrue(sql.contains("setval(pg_get_serial_sequence('saved_requests'"), "PostgreSQL V2 must sync saved requests sequence");
    }

    @Test
    @DisplayName("Entity Validation: SavedRequestEntity and RequestHistoryEntity must not require LONGTEXT")
    void testEntityColumnDefinitions() throws Exception {
        Field bodyField = SavedRequestEntity.class.getDeclaredField("body");
        Column bodyCol = bodyField.getAnnotation(Column.class);
        assertNotNull(bodyCol);
        assertNotEquals("LONGTEXT", bodyCol.columnDefinition(), "SavedRequestEntity body must not be hardcoded to LONGTEXT");

        Field reqBodyField = RequestHistoryEntity.class.getDeclaredField("requestBody");
        Column reqBodyCol = reqBodyField.getAnnotation(Column.class);
        assertNotNull(reqBodyCol);
        assertNotEquals("LONGTEXT", reqBodyCol.columnDefinition(), "RequestHistoryEntity requestBody must not be hardcoded to LONGTEXT");

        Field respBodyField = RequestHistoryEntity.class.getDeclaredField("responseBody");
        Column respBodyCol = respBodyField.getAnnotation(Column.class);
        assertNotNull(respBodyCol);
        assertNotEquals("LONGTEXT", respBodyCol.columnDefinition(), "RequestHistoryEntity responseBody must not be hardcoded to LONGTEXT");
    }
}
